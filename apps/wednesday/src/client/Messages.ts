import { Attachment } from '../shared/Attachments.ts'
import { Data, Schema } from 'effect'
import { ServerEvent, ModelMapping, Thinking, ApiFormat, MessageReply } from '../shared/protocol.ts'

export const PendingUpload = Schema.Struct({
  id: Schema.String,
  name: Schema.String,
  mediaType: Schema.String,
  source: Schema.String,
  progress: Schema.Number,
})
export type PendingUpload = typeof PendingUpload.Type

const MessageSchema = Schema.TaggedUnion({
  SessionChanged: { userId: Schema.String },
  Received: { event: ServerEvent },
  Failed: { message: Schema.String },
  Completed: {},
  SelectedProvider: { provider: Schema.Literals(['api', 'chatgpt']) },
  SelectedApiFormat: { format: ApiFormat },
  StartChatGpt: {},
  PollChatGpt: {},
  CancelChatGpt: {},
  DisconnectChatGpt: {},
  SelectedReply: { reply: MessageReply },
  CancelledReply: {},
  UploadStarted: { upload: PendingUpload },
  UploadProgress: { id: Schema.String, progress: Schema.Number },
  UploadCancelled: { id: Schema.String },
  AttachmentUploaded: { id: Schema.String, attachment: Attachment },
  UploadFailed: { id: Schema.String, message: Schema.String },
  RemovedAttachment: { id: Schema.String },
  ChangedDraft: { value: Schema.String },
  ChangedUrl: { value: Schema.String },
  ChangedKey: { value: Schema.String },
  SelectedMemoryModel: { id: Schema.String },
  SelectedModel: { id: Schema.String },
  SelectedThinking: { value: Schema.String },
  SelectedMemoryThinking: { value: Schema.String },
  OpenedPage: { page: Schema.Literals(['chat', 'settings']) },
  Send: { steer: Schema.Boolean },
  PreparedSubmission: {
    attachments: Schema.Array(Attachment),
    reply: Schema.optionalKey(MessageReply),
    requestId: Schema.String,
    text: Schema.String,
    date: Schema.String,
    mode: Schema.Literals(['send', 'steer']),
    turnId: Schema.NullOr(Schema.String),
  },
  SubmissionFailed: { requestId: Schema.String, message: Schema.String },
  RetriedSubmission: { requestId: Schema.String },
  Stop: {},
  SignOut: {},
  ResetSettings: {},
  CancelMapping: {},
  Reconnect: {},
  LoadOlder: {},
  Discover: {},
  Save: {},
  AutoSave: { revision: Schema.Int },
  SelectedMapping: { id: Schema.String },
  ChangedMapping: {
    field: Schema.Literals(['id', 'context', 'output']),
    value: Schema.String,
  },
  AppliedMapping: {},
  ValidatedMapping: { mapping: ModelMapping, revision: Schema.optionalKey(Schema.Int) },
  NewMapping: {},
  SelectedSettingsTab: { tab: Schema.Literals(['connection', 'models']) },
  PickedChatModel: { id: Schema.String },
  PickedChatThinking: { value: Thinking },
  AddedProviderField: { target: Schema.String, parentId: Schema.NullOr(Schema.Int) },
  RemovedProviderField: { target: Schema.String, id: Schema.Int },
  ChangedProviderField: {
    target: Schema.String,
    id: Schema.Int,
    field: Schema.Literals(['name', 'kind', 'value']),
    value: Schema.String,
  },
  ToggledThinkingLevel: { level: Thinking, enabled: Schema.Boolean },
  ToggledReasoning: { open: Schema.Boolean },
  DismissedFeedback: {},
})
export type Message = typeof MessageSchema.Type
export const Message = Data.taggedEnum<Message>()
export const matchMessage = MessageSchema.match
